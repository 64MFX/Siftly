/**
 * Renders an ArchiveDocument as a self-contained offline page (index.html) and
 * as Markdown (content.md). Both reference media with paths relative to the
 * tweet folder, so they work when opened straight from disk without Siftly.
 */
import type {
  ArchiveDocument,
  ArchivedArticle,
  ArchivedAuthor,
  ArchivedLinkCard,
  ArchivedMedia,
  ArchivedPoll,
  ArchivedQuote,
  ArticleBlock,
  TextSpan,
} from '@/lib/archive-types'

// ── Escaping ─────────────────────────────────────────────────────────────────

export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}

/** Only http(s) links leave the page — never javascript:, data:, etc. */
export function safeExternalHref(url: string | undefined): string | null {
  if (!url) return null
  try {
    const u = new URL(url)
    return u.protocol === 'http:' || u.protocol === 'https:' ? u.toString() : null
  } catch {
    return null
  }
}

/** Local media paths are generated by the archiver, but never trust them blindly */
function safeLocalPath(file: string | undefined): string | null {
  if (!file || file.startsWith('/') || file.includes('..') || /^[a-z]+:/i.test(file)) return null
  return file.split('/').map(encodeURIComponent).join('/')
}

function formatDate(iso: string | null | undefined): string {
  if (!iso) return ''
  const d = new Date(iso)
  if (isNaN(d.getTime())) return ''
  return d.toLocaleString('en-US', { dateStyle: 'medium', timeStyle: 'short', timeZone: 'UTC' }) + ' UTC'
}

const TEXT_TOKEN = /(https?:\/\/[^\s<>"']+)|(^|[^\w@])@(\w{1,15})\b/g

/** Escape text, turn URLs and @mentions into links, keep line breaks */
function richText(text: string): string {
  let out = ''
  let last = 0
  for (const match of text.matchAll(TEXT_TOKEN)) {
    const index = match.index ?? 0
    out += escapeHtml(text.slice(last, index))
    if (match[1]) {
      let url = match[1]
      let trailing = ''
      while (/[.,;:!?)\]]$/.test(url)) {
        trailing = url.slice(-1) + trailing
        url = url.slice(0, -1)
      }
      const href = safeExternalHref(url)
      out += href ? `<a href="${escapeHtml(href)}" rel="noopener noreferrer">${escapeHtml(url)}</a>` : escapeHtml(url)
      out += escapeHtml(trailing)
    } else {
      out += `${escapeHtml(match[2])}<a href="https://x.com/${escapeHtml(match[3])}" rel="noopener noreferrer">@${escapeHtml(match[3])}</a>`
    }
    last = index + match[0].length
  }
  out += escapeHtml(text.slice(last))
  return out.replace(/\n/g, '<br>')
}

// ── HTML pieces ──────────────────────────────────────────────────────────────

function mediaHtml(m: ArchivedMedia): string {
  const file = safeLocalPath(m.file)
  const poster = safeLocalPath(m.posterFile)
  const alt = escapeHtml(m.altText ?? '')
  const original = safeExternalHref(m.url)
  const missing = (label: string) =>
    `<div class="missing">${poster ? `<img src="${poster}" alt="">` : ''}<span>${label} wasn't saved${original ? ` — <a href="${escapeHtml(original)}" rel="noopener noreferrer">original</a>` : ''}</span></div>`

  if (m.type === 'photo') {
    return file ? `<a href="${file}"><img src="${file}" alt="${alt}" loading="lazy"></a>` : missing('Image')
  }
  if (!file) return missing(m.type === 'gif' ? 'GIF' : 'Video')
  const posterAttr = poster ? ` poster="${poster}"` : ''
  return m.type === 'gif'
    ? `<video src="${file}"${posterAttr} autoplay loop muted playsinline></video>`
    : `<video src="${file}"${posterAttr} controls preload="metadata" playsinline></video>`
}

function mediaGridHtml(media: ArchivedMedia[]): string {
  if (media.length === 0) return ''
  return `<div class="media-grid count-${Math.min(media.length, 4)}">${media.map(mediaHtml).join('')}</div>`
}

function avatarHtml(author: ArchivedAuthor, size: 'lg' | 'sm' = 'lg'): string {
  const file = safeLocalPath(author.avatarFile)
  if (file) return `<img class="avatar ${size}" src="${file}" alt="">`
  const initials = (author.name || author.handle || '?').trim().slice(0, 1).toUpperCase()
  return `<div class="avatar ${size} initials">${escapeHtml(initials)}</div>`
}

function authorHtml(author: ArchivedAuthor, date: string | null, size: 'lg' | 'sm' = 'lg'): string {
  const handle = author.handle && author.handle !== 'unknown' ? `@${escapeHtml(author.handle)}` : ''
  const when = formatDate(date)
  return `<div class="author ${size}">${avatarHtml(author, size)}<div><div class="name">${escapeHtml(author.name || 'Unknown')}</div><div class="meta">${[handle, escapeHtml(when)].filter(Boolean).join(' · ')}</div></div></div>`
}

function spansHtml(spans: TextSpan[]): string {
  return spans
    .map((s) => {
      let html = escapeHtml(s.text).replace(/\n/g, '<br>')
      if (s.code) html = `<code>${html}</code>`
      if (s.bold) html = `<strong>${html}</strong>`
      if (s.italic) html = `<em>${html}</em>`
      if (s.strike) html = `<s>${html}</s>`
      const href = safeExternalHref(s.href)
      if (href) html = `<a href="${escapeHtml(href)}" rel="noopener noreferrer">${html}</a>`
      return html
    })
    .join('')
}

function blockHtml(block: ArticleBlock): string {
  switch (block.type) {
    case 'paragraph':
      return `<p>${spansHtml(block.spans)}</p>`
    case 'heading1':
      return `<h2>${spansHtml(block.spans)}</h2>`
    case 'heading2':
      return `<h3>${spansHtml(block.spans)}</h3>`
    case 'heading3':
      return `<h4>${spansHtml(block.spans)}</h4>`
    case 'blockquote':
      return `<blockquote>${spansHtml(block.spans)}</blockquote>`
    case 'unordered-list':
    case 'ordered-list': {
      const tag = block.type === 'ordered-list' ? 'ol' : 'ul'
      return `<${tag}>${block.items.map((item) => `<li>${spansHtml(item)}</li>`).join('')}</${tag}>`
    }
    case 'code':
      return `<pre><code>${escapeHtml(block.text)}</code></pre>`
    case 'media':
      return `<figure>${block.media.map(mediaHtml).join('')}${block.caption ? `<figcaption>${escapeHtml(block.caption)}</figcaption>` : ''}</figure>`
    case 'embedded-tweet': {
      const href = safeExternalHref(block.tweetUrl)
      const who = block.authorName ? `<div class="name">${escapeHtml(block.authorName)}${block.authorHandle ? ` <span class="meta">@${escapeHtml(block.authorHandle)}</span>` : ''}</div>` : ''
      const body = block.text ? `<div class="text">${richText(block.text)}</div>` : '<div class="meta">Embedded post</div>'
      return `<div class="embed">${who}${body}${href ? `<a class="meta" href="${escapeHtml(href)}" rel="noopener noreferrer">View on X ↗</a>` : ''}</div>`
    }
    case 'divider':
      return '<hr>'
  }
}

function articleHtml(article: ArchivedArticle): string {
  const cover = article.coverImage ? `<div class="cover">${mediaHtml(article.coverImage)}</div>` : ''
  const body = article.blocks.length > 0
    ? article.blocks.map(blockHtml).join('\n')
    : `<p>${escapeHtml(article.previewText ?? '')}</p><p class="note">Only the article preview was available when this was saved.</p>`
  return `<article class="x-article">${cover}<h1>${escapeHtml(article.title || 'Untitled article')}</h1>${body}</article>`
}

function cardHtml(card: ArchivedLinkCard): string {
  const href = safeExternalHref(card.url)
  const image = safeLocalPath(card.imageFile)
  const inner = `${image ? `<img src="${image}" alt="">` : ''}<div class="card-body"><div class="card-title">${escapeHtml(card.title)}</div>${card.description ? `<div class="card-desc">${escapeHtml(card.description)}</div>` : ''}${card.domain ? `<div class="meta">${escapeHtml(card.domain)}</div>` : ''}</div>`
  return href ? `<a class="card" href="${escapeHtml(href)}" rel="noopener noreferrer">${inner}</a>` : `<div class="card">${inner}</div>`
}

function pollHtml(poll: ArchivedPoll): string {
  const total = poll.choices.reduce((sum, c) => sum + (c.votes ?? 0), 0)
  const rows = poll.choices.map((c) => {
    const pct = total > 0 && c.votes !== undefined ? Math.round((c.votes / total) * 100) : null
    return `<div class="poll-row"><div class="poll-bar" style="width:${pct ?? 0}%"></div><span>${escapeHtml(c.label)}</span>${pct !== null ? `<span class="meta">${pct}%</span>` : ''}</div>`
  })
  return `<div class="poll">${rows.join('')}${total > 0 ? `<div class="meta">${total.toLocaleString('en-US')} votes</div>` : ''}</div>`
}

function quoteHtml(quote: ArchivedQuote): string {
  const href = safeExternalHref(quote.tweetUrl)
  if (quote.unavailable && !quote.text && quote.media.length === 0) {
    return `<div class="quote"><div class="meta">Quoted post unavailable</div></div>`
  }
  return `<div class="quote">${authorHtml(quote.author, quote.createdAt, 'sm')}${quote.text ? `<div class="text">${richText(quote.text)}</div>` : ''}${mediaGridHtml(quote.media)}${href ? `<a class="meta" href="${escapeHtml(href)}" rel="noopener noreferrer">View quoted post on X ↗</a>` : ''}</div>`
}

