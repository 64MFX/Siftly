export function renderArchiveHtml(doc: ArchiveDocument): string {
  const title = doc.article?.title || `${doc.author.name || doc.author.handle} on X`
  const original = safeExternalHref(doc.tweetUrl)
  const banner = `<div class="banner${doc.unavailableOnX ? ' gone' : ''}"><span>${doc.unavailableOnX ? 'This post was no longer available on X — ' : ''}Saved locally by Siftly on ${escapeHtml(formatDate(doc.archivedAt))}</span>${original ? `<a href="${escapeHtml(original)}" rel="noopener noreferrer">Original post ↗</a>` : ''}</div>`

  const body = [
    banner,
    authorHtml(doc.author, doc.createdAt),
    doc.text ? `<div class="text">${richText(doc.text)}</div>` : '',
    mediaGridHtml(doc.media),
    doc.poll ? pollHtml(doc.poll) : '',
    doc.card ? cardHtml(doc.card) : '',
    doc.quote ? quoteHtml(doc.quote) : '',
    doc.article ? articleHtml(doc.article) : '',
  ].filter(Boolean).join('\n')

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="Siftly">
<title>${escapeHtml(title)}</title>
<style>${STYLES}</style>
</head>
<body>
<main class="wrap">
${body}
</main>
</body>
</html>
`
}

// ── Markdown ─────────────────────────────────────────────────────────────────

function mdSpans(spans: TextSpan[]): string {
  return spans
    .map((s) => {
      if (!s.text.trim()) return s.text
      const lead = s.text.match(/^\s*/)?.[0] ?? ''
      const tail = s.text.match(/\s*$/)?.[0] ?? ''
      let core = s.text.trim()
      if (s.code) core = `\`${core}\``
      if (s.bold) core = `**${core}**`
      if (s.italic) core = `_${core}_`
      if (s.strike) core = `~~${core}~~`
      const href = safeExternalHref(s.href)
      if (href) core = `[${core}](${href})`
      return `${lead}${core}${tail}`
    })
    .join('')
}

function mdMedia(m: ArchivedMedia): string {
  const file = safeLocalPath(m.file)
  const poster = safeLocalPath(m.posterFile)
  if (m.type === 'photo') return file ? `![${m.altText ?? 'Image'}](${file})` : `[Image (not saved)](${m.url})`
  const label = m.type === 'gif' ? 'GIF' : 'Video'
  if (!file) return `[${label} (not saved)](${m.url})`
  return `${poster ? `![${label} poster](${poster})\n` : ''}[▶ ${label}](${file})`
}

function mdBlock(block: ArticleBlock): string {
  switch (block.type) {
    case 'paragraph':
      return mdSpans(block.spans)
    case 'heading1':
      return `## ${mdSpans(block.spans)}`
    case 'heading2':
      return `### ${mdSpans(block.spans)}`
    case 'heading3':
      return `#### ${mdSpans(block.spans)}`
    case 'blockquote':
      return mdSpans(block.spans).split('\n').map((l) => `> ${l}`).join('\n')
    case 'unordered-list':
      return block.items.map((item) => `- ${mdSpans(item)}`).join('\n')
    case 'ordered-list':
      return block.items.map((item, i) => `${i + 1}. ${mdSpans(item)}`).join('\n')
    case 'code':
      return `\`\`\`\n${block.text}\n\`\`\``
    case 'media':
      return [...block.media.map(mdMedia), ...(block.caption ? [`_${block.caption}_`] : [])].join('\n\n')
    case 'embedded-tweet': {
      const who = block.authorHandle ? `@${block.authorHandle}` : 'Embedded post'
      const text = block.text ? `\n> ${block.text.split('\n').join('\n> ')}` : ''
      return `> **${who}** — [view on X](${block.tweetUrl})${text}`
    }
    case 'divider':
      return '---'
  }
}

export function renderArchiveMarkdown(doc: ArchiveDocument): string {
  const lines: string[] = []
  const handle = doc.author.handle && doc.author.handle !== 'unknown' ? ` (@${doc.author.handle})` : ''
  lines.push(`# ${doc.article?.title || `Post by ${doc.author.name || doc.author.handle}`}`)
  lines.push('')
  lines.push(`**Author:** ${doc.author.name}${handle}  `)
  if (doc.createdAt) lines.push(`**Posted:** ${formatDate(doc.createdAt)}  `)
  lines.push(`**Original:** ${doc.tweetUrl}  `)
  lines.push(`**Saved:** ${formatDate(doc.archivedAt)}${doc.unavailableOnX ? ' (no longer available on X)' : ''}`)
  lines.push('')
  lines.push('---')

  if (doc.text) lines.push('', doc.text)
  for (const m of doc.media) lines.push('', mdMedia(m))

  if (doc.poll) {
    lines.push('')
    for (const c of doc.poll.choices) lines.push(`- ${c.label}${c.votes !== undefined ? ` — ${c.votes} votes` : ''}`)
  }

  if (doc.card) {
    lines.push('', `> **[${doc.card.title}](${doc.card.url})**`)
    if (doc.card.description) lines.push(`> ${doc.card.description}`)
    if (doc.card.imageFile) lines.push('>', `> ![](${safeLocalPath(doc.card.imageFile)})`)
  }

  if (doc.quote) {
    const q = doc.quote
    lines.push('', `> **Quoting @${q.author.handle || 'unknown'}** — [view on X](${q.tweetUrl})`)
    if (q.text) lines.push(`> ${q.text.split('\n').join('\n> ')}`)
    for (const m of q.media) lines.push('>', `> ${mdMedia(m).split('\n').join('\n> ')}`)
  }

  if (doc.article) {
    const a = doc.article
    lines.push('', '---', '')
    if (a.coverImage) lines.push(mdMedia(a.coverImage), '')
    lines.push(`## ${a.title || 'Untitled article'}`)
    if (a.blocks.length === 0) {
      if (a.previewText) lines.push('', a.previewText)
      lines.push('', '_Only the article preview was available when this was saved._')
    }
    for (const block of a.blocks) lines.push('', mdBlock(block))
  }

  return lines.join('\n') + '\n'
}
